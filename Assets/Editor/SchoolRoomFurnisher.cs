    private static MeshRenderer FindFloor(List<MeshRenderer> renderers, string roomId)
    {
        string target = roomId + "_Floor";
        foreach (MeshRenderer r in renderers)
        {
            if (r.gameObject.name == target) return r;
        }
        return null;
    }

    /// <summary>
    /// Collects the world positions of THIS room's own doorway transoms. A room's
    /// transoms are named "&lt;roomid&gt;_&lt;N|S|E|W&gt;_Seg#_..._Transom"; matching on the
    /// direction token immediately after the id avoids grabbing sub-rooms (e.g.
    /// "library" must not pick up "library_basement_*"). "AntiZFightCover" variants
    /// are ignored, and generated-door transoms (prefixed "Door_") never match.
    /// </summary>
    private static List<Vector3> CollectDoorways(List<MeshRenderer> renderers, string roomId)
    {
        List<Vector3> result = new List<Vector3>();
        string[] prefixes =
        {
            roomId + "_N_", roomId + "_S_", roomId + "_E_", roomId + "_W_",
        };

        foreach (MeshRenderer r in renderers)
        {
            string n = r.gameObject.name;
            if (!n.Contains("Transom")) continue;
            if (n.Contains("AntiZFightCover")) continue;

            bool mine = false;
            foreach (string p in prefixes)
            {
                if (n.StartsWith(p)) { mine = true; break; }
            }
            if (!mine) continue;

            result.Add(r.bounds.center);
        }
        return result;
    }


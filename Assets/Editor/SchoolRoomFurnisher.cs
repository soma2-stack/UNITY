/// <summary>
/// Furnishes EVERY non-stair room of the School Of The Dead map with simple,
/// type-appropriate props so the level reads as a believable (but dark and
/// abandoned) school instead of empty boxes.
///
/// HOW IT WORKS
/// ------------
/// The whole map sits under a root ("School Map - Zombies Scale") scaled to 0.4,
/// so local positions are meaningless. This tool therefore works ENTIRELY in
/// WORLD space:
///   * A room is located/sized by its "&lt;roomid&gt;_Floor" MeshRenderer world
///     bounds. The floor-top Y (bounds.max.y) is where every prop's base sits.
///   * Doorways are kept clear using the world positions of the room's own
///     transoms ("&lt;roomid&gt;_&lt;N|S|E|W&gt;_Seg#_..._Transom", ignoring the
///     "AntiZFightCover" variants).
///
/// Props are crude primitive constructions (cubes mostly) on dark, grimy
/// materials - this tool owns LAYOUT/STRUCTURE, not final art.
///
/// RE-RUNNABLE &amp; NON-DESTRUCTIVE
/// ----------------------------
/// Everything is created under a single root "Generated_RoomProps" that is
/// destroyed and rebuilt each run. The tool never edits, moves, or deletes any
/// existing scene object; it only creates props (and "Furniture - *" materials).
/// Layout is deterministic (RNG seeded from the room id) so re-runs reproduce
/// the same arrangement.
/// </summary>
public static class SchoolRoomFurnisher
{
    private const string ScenePath = "Assets/Scenes/SchoolOfTheDead.unity";
    private const string MaterialFolder = "Assets/Materials/SchoolOfTheDead";
    private const string RootName = "Generated_RoomProps";

    // World-space margins / clearances.
    private const float WallInset = 0.8f;       // keep props ~0.8m off the walls
    private const float DoorClearRadius = 1.8f; // keep a clear bubble at each doorway

    // Roughly one prop per this many square metres of floor (rooms are capped per type too).
    private const float SqMetresPerProp = 7f;

    // Roots that are generated by this or other tools - never treat as rooms / scan for floors.

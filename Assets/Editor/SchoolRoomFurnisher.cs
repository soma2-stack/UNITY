        // Chair on the wall side of the desk, facing into the room like the desk.
        Vector3 cp = new Vector3(x, ctx.FloorY, z) - inward * 0.7f;
        if (ctx.Fits(cp.x, cp.z, 0.28f, 0.28f)) MakeChair(ctx, cp, yaw, chairName);

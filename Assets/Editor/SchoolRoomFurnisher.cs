    /// <summary>
    /// Creates an empty prop root parented under the room container, positioned at
    /// the given world point. For floor-standing props the caller passes a base
    /// point carrying ctx.FloorY and builds children upward from local Y=0; for a
    /// surface-mounted item (e.g. a monitor) the caller passes the explicit world
    /// centre instead.
    /// </summary>
    private static GameObject MakeRoot(RoomContext ctx, string name, Vector3 basePos, float yaw)
    {
        GameObject g = new GameObject(name);
        g.transform.SetParent(ctx.Parent, false);
        g.transform.position = basePos;
        g.transform.rotation = Quaternion.Euler(0f, yaw, 0f);
        g.transform.localScale = Vector3.one; // parent (room container) is unscaled
        return g;
    }

    private static GameObject AddBox(Transform parent, string name, Material mat, Vector3 localPos, Vector3 localScale, bool keepCollider)
    {
        GameObject box = GameObject.CreatePrimitive(PrimitiveType.Cube);
        box.name = name;
        box.transform.SetParent(parent, false);
        box.transform.localPosition = localPos;
        box.transform.localRotation = Quaternion.identity;
        box.transform.localScale = localScale;
        FinishPrimitive(box, mat, keepCollider);
        return box;
    }

    private static GameObject AddCylinder(Transform parent, string name, Material mat, Vector3 localPos, Vector3 localScale, bool keepCollider)
    {
        GameObject cyl = GameObject.CreatePrimitive(PrimitiveType.Cylinder);
        cyl.name = name;
        cyl.transform.SetParent(parent, false);
        cyl.transform.localPosition = localPos;
        cyl.transform.localRotation = Quaternion.identity;
        cyl.transform.localScale = localScale;
        FinishPrimitive(cyl, mat, keepCollider);
        return cyl;
    }

    private static void FinishPrimitive(GameObject go, Material mat, bool keepCollider)
    {
        if (!keepCollider)
        {
            Collider col = go.GetComponent<Collider>();
            if (col != null) Object.DestroyImmediate(col);
        }

        MeshRenderer mr = go.GetComponent<MeshRenderer>();
        if (mr != null) mr.sharedMaterial = mat;
        go.isStatic = true;
    }


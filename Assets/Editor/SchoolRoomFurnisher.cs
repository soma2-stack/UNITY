    // === Placement helpers =================================================

    private enum Wall { North, South, East, West } // +Z, -Z, +X, -X

    /// <summary>
    /// Tries to place a prop centred at world (x,z) on the floor, validating the
    /// given half-footprint first. Returns true and invokes the builder if it fits.
    /// </summary>
    private static bool PlaceAt(RoomContext ctx, float x, float z, float halfX, float halfZ, System.Action<Vector3> build)
    {
        if (!ctx.Fits(x, z, halfX, halfZ)) return false;
        build(new Vector3(x, ctx.FloorY, z));
        return true;
    }

    /// <summary>
    /// Places a prop tucked into the given corner (0=SW,1=SE,2=NW,3=NE), inset by
    /// the prop's half extents so it sits against the walls without clipping.
    /// The yaw passed to the builder faces the prop's "back" toward the corner.
    /// </summary>
    private static void PlaceInCorner(RoomContext ctx, int corner, float halfX, float halfZ, System.Action<Vector3, float> build)
    {
        bool east = (corner == 1 || corner == 3);
        bool north = (corner == 2 || corner == 3);

        float x = east ? ctx.MaxX - halfX : ctx.MinX + halfX;
        float z = north ? ctx.MaxZ - halfZ : ctx.MinZ + halfZ;
        float yaw = north ? 180f : 0f;

        if (ctx.Fits(x, z, halfX, halfZ))
        {
            build(new Vector3(x, ctx.FloorY, z), yaw);
        }
    }

    /// <summary>
    /// Geometry of one wall in WORLD space. <paramref name="fixedX"/>/<paramref name="fixedZ"/>
    /// give the wall line; <paramref name="runsAlongX"/> is true for N/S walls
    /// (the run length lies on world X), false for E/W walls (run on world Z).
    /// <paramref name="inwardSign"/> is +1 or -1 along the wall NORMAL axis, pointing
    /// from the wall toward the room interior. Wall-run builders keep their roots
    /// UNROTATED and align geometry to world axes using these, so box shapes are
    /// never double-rotated.
    /// </summary>
    private static void WallInfo(RoomContext ctx, Wall wall, out float fixedX, out float fixedZ, out bool runsAlongX, out float inwardSign)
    {
        switch (wall)
        {
            case Wall.North: fixedX = 0f; fixedZ = ctx.MaxZ; runsAlongX = true; inwardSign = -1f; break; // interior is -Z
            case Wall.South: fixedX = 0f; fixedZ = ctx.MinZ; runsAlongX = true; inwardSign = +1f; break; // interior is +Z
            case Wall.East: fixedX = ctx.MaxX; fixedZ = 0f; runsAlongX = false; inwardSign = -1f; break; // interior is -X
            default: fixedX = ctx.MinX; fixedZ = 0f; runsAlongX = false; inwardSign = +1f; break;        // West, interior is +X
        }
    }

    // === Facing / orientation helpers ======================================
    //
    // FACING CONVENTION (used by every chair/desk/seat in this tool):
    //   A prop built by MakeDesk/MakeChair/etc. has its "front" (the side a person
    //   sits at, the back of a chair, the working edge of a desk) on local +Z.
    //   So a yaw of 0 makes the occupant FACE world +Z; +90 -> +X; 180 -> -Z;
    //   270 -> -X. YawFromDir converts any world direction into that yaw, so all
    //   facing is derived deterministically from room geometry (wall normals).

    /// <summary>Yaw (degrees) that makes a prop's local +Z point along <paramref name="dir"/> (world X/Z).</summary>
    private static float YawFromDir(Vector3 dir)
    {
        if (dir.sqrMagnitude < 1e-6f) return 0f;
        return Mathf.Atan2(dir.x, dir.z) * Mathf.Rad2Deg;
    }

    /// <summary>Unit world direction pointing from the wall INTO the room interior.</summary>
    private static Vector3 InwardNormal(Wall wall)
    {
        switch (wall)
        {
            case Wall.North: return new Vector3(0f, 0f, -1f);
            case Wall.South: return new Vector3(0f, 0f, 1f);
            case Wall.East: return new Vector3(-1f, 0f, 0f);
            default: return new Vector3(1f, 0f, 0f); // West
        }
    }

    /// <summary>
    /// Picks the classroom "front" (board/teacher) wall: the wall whose nearest
    /// doorway is FARTHEST away, so desks never face a door. Ties (e.g. no doorways
    /// at all) are broken toward the wall that gives the WIDER board / more columns
    /// of desks, then deterministically. Pure read of room geometry.
    /// </summary>
    private static Wall ChooseFrontWall(RoomContext ctx)
    {
        Wall[] walls = { Wall.North, Wall.South, Wall.East, Wall.West };
        Wall best = Wall.North;
        float bestScore = float.NegativeInfinity;

        foreach (Wall w in walls)
        {
            WallInfo(ctx, w, out float fx, out float fz, out bool alongX, out _);
            float wallLine = alongX ? fz : fx;

            // Nearest doorway, measured perpendicular to this wall line.
            float nearest = float.PositiveInfinity;
            foreach (Vector3 d in ctx.Doorways)
            {
                float perp = alongX ? Mathf.Abs(d.z - wallLine) : Mathf.Abs(d.x - wallLine);
                if (perp < nearest) nearest = perp;
            }
            if (float.IsPositiveInfinity(nearest)) nearest = 1000f; // no doorways on/near this wall

            // Prefer distance-from-doors first; small bonus for a wider board so the
            // teacher faces down the long axis when doors are equivalent.
            float wallWidth = alongX ? ctx.SizeX : ctx.SizeZ;
            float score = nearest * 10f + wallWidth;

            if (score > bestScore)
            {
                bestScore = score;
                best = w;
            }
        }
        return best;
    }

    /// <summary>World-aligned box scale for a wall-run piece: <paramref name="runLen"/>
    /// along the run axis, <paramref name="depth"/> along the wall-normal axis.</summary>
    private static Vector3 WallBoxScale(bool runsAlongX, float runLen, float height, float depth)
    {
        return runsAlongX ? new Vector3(runLen, height, depth) : new Vector3(depth, height, runLen);
    }

    /// <summary>World offset along the wall-normal axis (inward = positive distance).</summary>
    private static Vector3 NormalOffset(bool runsAlongX, float inwardSign, float distance)
    {
        return runsAlongX ? new Vector3(0f, 0f, inwardSign * distance) : new Vector3(inwardSign * distance, 0f, 0f);
    }

    /// <summary>World offset along the run axis.</summary>
    private static Vector3 RunOffset(bool runsAlongX, float distance)
    {
        return runsAlongX ? new Vector3(distance, 0f, 0f) : new Vector3(0f, 0f, distance);
    }

    // === Composite wall-run builders =======================================

    /// <summary>
    /// A run of counters along a wall. <paramref name="wallOffset"/> pushes the
    /// counter's BACK face this far off the wall line (into the room) so the player
    /// can walk behind it - used for cafeteria/kitchen service lines. 0 keeps it
    /// flush (the default for lab benches against the wall). If the room is too
    /// shallow for the requested offset it is reduced so the counter still fits.
    /// </summary>
    private static void MakeCounterRun(RoomContext ctx, Wall wall, string label, bool withSink, float wallOffset = 0f)
    {
        WallInfo(ctx, wall, out float fx, out float fz, out bool alongX, out float inward);
        const float depth = 0.6f, height = 0.9f, segLen = 1.2f;
        float runMin = alongX ? ctx.MinX : ctx.MinZ;
        float runMax = alongX ? ctx.MaxX : ctx.MaxZ;
        float wallLine = alongX ? fz : fx;

        // Clamp the walk-behind offset so the counter body still lands inside the
        // inset room rectangle on the wall-normal axis.
        float roomDepth = alongX ? ctx.SizeZ : ctx.SizeX;
        float maxOffset = Mathf.Max(0f, roomDepth - depth - 0.6f);
        float offset = Mathf.Clamp(wallOffset, 0f, maxOffset);

        int seg = 0;
        for (float t = runMin + segLen * 0.5f; t + segLen * 0.5f <= runMax; t += segLen, seg++)
        {
            // Body back face sits 'offset' off the wall, pushed inward by half its depth.
            float runC = t;
            float normC = wallLine + inward * (offset + depth * 0.5f);
            float x = alongX ? runC : normC;
            float z = alongX ? normC : runC;
            float hx = alongX ? segLen * 0.5f : depth * 0.5f;
            float hz = alongX ? depth * 0.5f : segLen * 0.5f;
            if (!ctx.Fits(x, z, hx, hz)) continue;

            Vector3 pos = new Vector3(x, ctx.FloorY, z);
            GameObject g = MakeRoot(ctx, $"{label}_{seg}", pos, 0f); // identity; world-aligned below
            AddBox(g.transform, "Body", _matMetalGrey, new Vector3(0f, height * 0.5f, 0f),
                WallBoxScale(alongX, segLen, height, depth), true);
            AddBox(g.transform, "Top", _matMetalDark, new Vector3(0f, height + 0.02f, 0f),
                WallBoxScale(alongX, segLen + 0.05f, 0.05f, depth + 0.05f), false);
            if (withSink && seg == 0)
            {
                AddBox(g.transform, "SinkBasin", _matMetalDark, new Vector3(0f, height - 0.08f, 0f),
                    new Vector3(0.4f, 0.16f, 0.4f), false);
            }
            ctx.Count();
        }
    }

    private static void MakeWallShelfRun(RoomContext ctx, Wall wall, string label)
    {
        WallInfo(ctx, wall, out float fx, out float fz, out bool alongX, out float inward);
        const float depth = 0.4f, segLen = 1.6f, height = 1.8f, board = 0.05f;
        float runMin = alongX ? ctx.MinX : ctx.MinZ;
        float runMax = alongX ? ctx.MaxX : ctx.MaxZ;
        float wallLine = alongX ? fz : fx;

        int seg = 0;
        for (float t = runMin + segLen * 0.5f; t + segLen * 0.5f <= runMax; t += segLen + 0.1f, seg++)
        {
            float normC = wallLine + inward * depth * 0.5f;
            float x = alongX ? t : normC;
            float z = alongX ? normC : t;
            float hx = alongX ? segLen * 0.5f : depth * 0.5f;
            float hz = alongX ? depth * 0.5f : segLen * 0.5f;
            if (!ctx.Fits(x, z, hx, hz)) continue;

            // World-aligned shelf unit (identity root): 2 uprights + 3 boards.
            GameObject g = MakeRoot(ctx, $"{label}_{seg}", new Vector3(x, ctx.FloorY, z), 0f);
            float halfRun = segLen * 0.5f - board * 0.5f;
            AddBox(g.transform, "Upright_A", _matWoodDark, RunOffset(alongX, -halfRun) + Vector3.up * (height * 0.5f),
                WallBoxScale(alongX, board, height, depth), true);
            AddBox(g.transform, "Upright_B", _matWoodDark, RunOffset(alongX, halfRun) + Vector3.up * (height * 0.5f),
                WallBoxScale(alongX, board, height, depth), true);
            for (int s = 0; s < 3; s++)
            {
                float y = Mathf.Lerp(0.1f, height - 0.1f, s / 2f);
                AddBox(g.transform, $"Board_{s}", _matWoodMid, Vector3.up * y,
                    WallBoxScale(alongX, segLen, board, depth), false);
            }
            ctx.Count();
        }
    }

    private static void MakePipeRun(RoomContext ctx, Wall wall, string label)
    {
        WallInfo(ctx, wall, out float fx, out float fz, out bool alongX, out float inward);
        float runMin = alongX ? ctx.MinX : ctx.MinZ;
        float runMax = alongX ? ctx.MaxX : ctx.MaxZ;
        float len = runMax - runMin;
        if (len < 1f) return;

        float t = (runMin + runMax) * 0.5f;
        const float depth = 0.2f;
        float wallLine = alongX ? fz : fx;
        float normC = wallLine + inward * depth;
        float x = alongX ? t : normC;
        float z = alongX ? normC : t;

        Vector3 pos = new Vector3(x, ctx.FloorY, z);
        GameObject g = MakeRoot(ctx, label, pos, 0f); // identity; pipes rotated to world axis
        // Two horizontal pipes at different heights, running along the wall axis.
        // A cylinder's long axis is local Y: rotate 90 about Z to lie along world X,
        // or 90 about X to lie along world Z.
        Quaternion lie = alongX ? Quaternion.Euler(0f, 0f, 90f) : Quaternion.Euler(90f, 0f, 0f);
        for (int i = 0; i < 2; i++)
        {
            float py = 1.1f + i * 0.6f;
            GameObject pipe = AddCylinder(g.transform, $"Pipe_{i}", _matRust,
                new Vector3(0f, py, 0f), new Vector3(0.12f, len * 0.45f, 0.12f), true);
            pipe.transform.localRotation = lie;
        }
        ctx.Count();
    }

    private static void MakeBleacher(RoomContext ctx, Wall wall, string label)
    {
        WallInfo(ctx, wall, out float fx, out float fz, out bool alongX, out float inward);
        float runMin = alongX ? ctx.MinX : ctx.MinZ;
        float runMax = alongX ? ctx.MaxX : ctx.MaxZ;
        float len = Mathf.Min(runMax - runMin - 1f, 8f);
        if (len < 2f) return;

        const int steps = 4;
        const float depthPerStep = 0.5f, heightPerStep = 0.4f;
        float totalDepth = steps * depthPerStep;
        float t = (runMin + runMax) * 0.5f;
        float wallLine = alongX ? fz : fx;
        // Centre the block so it sits against the wall, extending inward.
        float normC = wallLine + inward * totalDepth * 0.5f;
        float x = alongX ? t : normC;
        float z = alongX ? normC : t;

        float hx = alongX ? len * 0.5f : totalDepth * 0.5f;
        float hz = alongX ? totalDepth * 0.5f : len * 0.5f;
        if (!ctx.Fits(x, z, hx, hz)) return;

        Vector3 pos = new Vector3(x, ctx.FloorY, z);
        GameObject g = MakeRoot(ctx, label, pos, 0f); // identity; world-aligned risers
        for (int s = 0; s < steps; s++)
        {
            // Risers get taller toward the wall (outward = -inward from this centre).
            float along = -inward * (s - (steps - 1) * 0.5f) * depthPerStep;
            float h = (s + 1) * heightPerStep;
            AddBox(g.transform, $"Step_{s}", _matMetalGrey,
                NormalOffset(alongX, 1f, along) + Vector3.up * (h * 0.5f),
                WallBoxScale(alongX, len, h, depthPerStep), true);
        }
        ctx.Count();
    }

    private static void MakeLockerBankWall(RoomContext ctx, Wall wall, string label)
    {
        WallInfo(ctx, wall, out float fx, out float fz, out bool alongX, out float inward);
        const float lockerW = 0.45f, lockerH = 1.9f, depth = 0.45f;
        float runMin = alongX ? ctx.MinX : ctx.MinZ;
        float runMax = alongX ? ctx.MaxX : ctx.MaxZ;
        int count = Mathf.Clamp(Mathf.FloorToInt((runMax - runMin) / lockerW) - 1, 2, 8);
        float totalW = count * lockerW;

        float t = (runMin + runMax) * 0.5f;
        float wallLine = alongX ? fz : fx;
        float normC = wallLine + inward * depth * 0.5f;
        float x = alongX ? t : normC;
        float z = alongX ? normC : t;
        float hx = alongX ? totalW * 0.5f : depth * 0.5f;
        float hz = alongX ? depth * 0.5f : totalW * 0.5f;
        if (!ctx.Fits(x, z, hx, hz)) return;

        Vector3 pos = new Vector3(x, ctx.FloorY, z);
        GameObject g = MakeRoot(ctx, label, pos, 0f); // identity; world-aligned
        float start = -totalW * 0.5f + lockerW * 0.5f;
        for (int i = 0; i < count; i++)
        {
            AddBox(g.transform, $"Locker_{i}", _matMetalGrey,
                RunOffset(alongX, start + i * lockerW) + Vector3.up * (lockerH * 0.5f),
                WallBoxScale(alongX, lockerW * 0.95f, lockerH, depth), true);
        }
        ctx.Count();
    }

    private static void MakeFilingCabinets(RoomContext ctx, Wall wall, string label)
    {
        // World-aligned (identity root). Body width spans the run axis, depth the
        // wall normal; drawer faces sit on the inward side.
        WallInfo(ctx, wall, out float fx, out float fz, out bool alongX, out float inward);
        const float w = 0.5f, h = 1.3f, depth = 0.6f;
        float runMin = alongX ? ctx.MinX : ctx.MinZ;
        float runMax = alongX ? ctx.MaxX : ctx.MaxZ;
        float wallLine = alongX ? fz : fx;
        int count = Mathf.Clamp(Mathf.FloorToInt((runMax - runMin) / (w + 0.1f)), 1, 3);

        int placed = 0;
        float t = runMin + w * 0.5f + 0.3f;
        for (int i = 0; i < count; i++, t += w + 0.15f)
        {
            float normC = wallLine + inward * depth * 0.5f;
            float x = alongX ? t : normC;
            float z = alongX ? normC : t;
            float hx = alongX ? w * 0.5f : depth * 0.5f;
            float hz = alongX ? depth * 0.5f : w * 0.5f;
            if (!ctx.Fits(x, z, hx, hz)) continue;

            Vector3 pos = new Vector3(x, ctx.FloorY, z);
            GameObject g = MakeRoot(ctx, $"{label}_{i}", pos, 0f);
            AddBox(g.transform, "Body", _matMetalDark, new Vector3(0f, h * 0.5f, 0f),
                WallBoxScale(alongX, w, h, depth), true);
            for (int d = 0; d < 3; d++)
            {
                float dy = 0.25f + d * 0.4f;
                AddBox(g.transform, $"Drawer_{d}", _matMetalGrey,
                    NormalOffset(alongX, inward, depth * 0.5f + 0.02f) + Vector3.up * dy,
                    WallBoxScale(alongX, w * 0.85f, 0.3f, 0.04f), false);
            }
            placed++;
        }
        if (placed > 0) ctx.Count();
    }


    [MenuItem("Tools/School Of The Dead/Furnish Rooms")]
    public static void FurnishRooms()
    {
        EnsureFolder("Assets/Materials");
        EnsureFolder(MaterialFolder);
        BuildMaterials();

        Scene scene = EditorSceneManager.OpenScene(ScenePath, OpenSceneMode.Single);

        // Re-runnable: destroy + recreate our single root at world origin, scale 1.
        GameObject root = RecreateRoot();

        // Gather every relevant renderer once (skipping generated roots), keyed by name.
        // We need exact "<roomid>_Floor" lookups and per-room transom collections.
        List<MeshRenderer> allRenderers = new List<MeshRenderer>();
        foreach (GameObject rootGo in scene.GetRootGameObjects())
        {
            if (IsGeneratedRoot(rootGo.name))
            {
                continue;
            }

            allRenderers.AddRange(rootGo.GetComponentsInChildren<MeshRenderer>(true));
        }

        int roomsFurnished = 0;
        int totalProps = 0;
        List<string> skipped = new List<string>();

        foreach ((string id, RoomType type) in Rooms)
        {
            MeshRenderer floor = FindFloor(allRenderers, id);
            if (floor == null)
            {
                skipped.Add($"{id} (no '{id}_Floor' in scene)");
                continue;
            }

            List<Vector3> doorways = CollectDoorways(allRenderers, id);

            // Per-room container for tidiness.
            GameObject roomGo = new GameObject(id);
            roomGo.transform.SetParent(root.transform, false);

            RoomContext ctx = new RoomContext(id, type, floor.bounds, doorways, roomGo.transform);

            int before = ctx.PropCount;
            Dispatch(ctx);
            int placed = ctx.PropCount - before;
            totalProps += placed;

            if (placed > 0)
            {
                roomsFurnished++;
            }
            else
            {
                // Room was found but nothing fit (too small / fully blocked). Keep the
                // empty container - harmless - but note it.
                skipped.Add($"{id} (found but no props fit)");
            }
        }

        EditorSceneManager.MarkSceneDirty(scene);
        EditorSceneManager.SaveScene(scene);
        AssetDatabase.SaveAssets();
        AssetDatabase.Refresh();

        string skipMsg = skipped.Count == 0 ? "none" : string.Join(", ", skipped);
        Debug.Log(
            $"[SchoolRoomFurnisher] Furnished {roomsFurnished} room(s) with {totalProps} prop(s) " +
            $"under '{RootName}'. Skipped: {skipMsg}. " +
            "Re-running rebuilds Generated_RoomProps from scratch (non-destructive).");
    }

    // === Per-room context ===================================================

    /// <summary>
    /// Everything a furnish method needs about one room, plus prop counting and
    /// the shared placement-validity test (inside footprint + clear of doorways).
    /// </summary>
    private sealed class RoomContext
    {
        public readonly string Id;
        public readonly RoomType Type;
        public readonly Bounds Floor;     // world bounds of the floor renderer
        public readonly float FloorY;     // world Y of the floor TOP (props sit here)
        public readonly List<Vector3> Doorways;
        public readonly Transform Parent; // per-room container
        public readonly System.Random Rng;

        // Inner (walkable / placeable) rectangle in world X/Z, shrunk by WallInset.
        public readonly float MinX, MaxX, MinZ, MaxZ;
        public readonly float SizeX, SizeZ, Area;

        public int PropCount { get; private set; }

        /// <summary>Room centre in world space, at the floor-top Y.</summary>
        public Vector3 Center => new Vector3(Floor.center.x, FloorY, Floor.center.z);

        public RoomContext(string id, RoomType type, Bounds floor, List<Vector3> doorways, Transform parent)
        {
            Id = id;
            Type = type;
            Floor = floor;
            FloorY = floor.max.y;
            Doorways = doorways;
            Parent = parent;
            Rng = new System.Random(StableHash(id));

            MinX = floor.min.x + WallInset;
            MaxX = floor.max.x - WallInset;
            MinZ = floor.min.z + WallInset;
            MaxZ = floor.max.z - WallInset;
            SizeX = Mathf.Max(0f, MaxX - MinX);
            SizeZ = Mathf.Max(0f, MaxZ - MinZ);
            Area = floor.size.x * floor.size.z;
        }

        public int PropBudget()
        {
            return Mathf.Max(1, Mathf.RoundToInt(Area / SqMetresPerProp));
        }

        public void Count() => PropCount++;

        /// <summary>
        /// True if an axis-aligned prop footprint (centred at world x/z, with the
        /// given half extents along X/Z after yaw is applied by the caller) fits
        /// inside the inset room rectangle and clears every doorway bubble.
        /// </summary>
        public bool Fits(float x, float z, float halfX, float halfZ)
        {
            if (x - halfX < MinX || x + halfX > MaxX) return false;
            if (z - halfZ < MinZ || z + halfZ > MaxZ) return false;

            float clearR = DoorClearRadius + Mathf.Max(halfX, halfZ);
            float clearSq = clearR * clearR;
            foreach (Vector3 d in Doorways)
            {
                float dx = d.x - x;
                float dz = d.z - z;
                if (dx * dx + dz * dz < clearSq) return false;
            }

            return true;
        }
    }

    private static void Dispatch(RoomContext ctx)
    {
        switch (ctx.Type)
        {
            case RoomType.Classroom: FurnishClassroom(ctx); break;
            case RoomType.ScienceLab: FurnishLab(ctx); break;
            case RoomType.Conference: FurnishConference(ctx); break;
            case RoomType.Cafeteria: FurnishCafeteria(ctx); break;
            case RoomType.Kitchen: FurnishKitchen(ctx); break;
            case RoomType.Library: FurnishLibrary(ctx); break;
            case RoomType.Gym: FurnishGym(ctx); break;
            case RoomType.Office: FurnishOffice(ctx); break;
            case RoomType.Security: FurnishSecurity(ctx); break;
            case RoomType.Nurse: FurnishNurse(ctx); break;
            case RoomType.Storage: FurnishStorage(ctx, janitor: false); break;
            case RoomType.Janitor: FurnishStorage(ctx, janitor: true); break;
            case RoomType.Utility: FurnishUtility(ctx); break;
            case RoomType.Courtyard: FurnishCourtyard(ctx); break;
        }
    }

    // === Per-type furnish methods ==========================================

    private static void FurnishClassroom(RoomContext ctx)
    {
        // Choose the "front" (board) wall deterministically: the wall farthest from
        // any doorway so desks never face a door. Everything below is oriented from
        // that wall's geometry, so the whole room reads consistently regardless of
        // which way the room happens to be aligned in world space.
        Wall front = ChooseFrontWall(ctx);
        WallInfo(ctx, front, out float ffx, out float ffz, out bool runAlongX, out _);

        // Axis abstraction. "depth" = perpendicular to the board (back wall -> front
        // wall); "run" = along the board (where columns of desks spread out).
        bool depthIsZ = runAlongX;                 // N/S front -> depth on Z; E/W front -> depth on X
        float frontCoord = depthIsZ ? ffz : ffx;   // world coord of the front wall on the depth axis
        float backCoord = depthIsZ
            ? (front == Wall.North ? ctx.MinZ : ctx.MaxZ)
            : (front == Wall.East ? ctx.MinX : ctx.MaxX);
        float depthSign = Mathf.Sign(frontCoord - backCoord);   // back -> front along depth
        float runMin = runAlongX ? ctx.MinX : ctx.MinZ;
        float runMax = runAlongX ? ctx.MaxX : ctx.MaxZ;
        float runCenter = 0.5f * (runMin + runMax);

        Vector3 inward = InwardNormal(front);       // board -> students
        Vector3 boardDir = -inward;                 // students -> board (what a student faces)
        float studentYaw = YawFromDir(boardDir);    // every student desk + chair uses this
        float teacherYaw = YawFromDir(inward);      // teacher faces the students

        // 1) Whiteboard on the chosen front wall (decorative, no collider).
        MakeWhiteboard(ctx, front, "Whiteboard");

        // 2) Teacher desk near the front wall, facing the students; chair tucked
        //    between the desk and the wall (occupant on the wall side).
        float teacherDepth = frontCoord - depthSign * 0.6f; // 0.6m off the board wall
        float tdx = depthIsZ ? runCenter : teacherDepth;
        float tdz = depthIsZ ? teacherDepth : runCenter;
        if (PlaceAt(ctx, tdx, tdz, 0.6f, 0.45f, p => MakeDesk(ctx, p, teacherYaw, "TeacherDesk")))
        {
            Vector3 tc = new Vector3(tdx, ctx.FloorY, tdz) + (-boardDir) * 0.7f; // wall side of desk
            if (ctx.Fits(tc.x, tc.z, 0.3f, 0.3f)) MakeChair(ctx, tc, teacherYaw, "TeacherChair");
        }

        // 3) Corner shelf + trash can (away from the board wall so they don't crowd it).
        PlaceInCorner(ctx, 0, 1.0f, 0.4f, (pos, yaw) => MakeShelf(ctx, pos, yaw, "Shelf"));
        PlaceInCorner(ctx, 2, 0.3f, 0.3f, (pos, yaw) => MakeTrashCan(ctx, pos, "TrashCan"));

        // 4) Neat rows of student desks, all FACING THE BOARD, chairs tucked behind
        //    each desk, with a clear central aisle running front-to-back so students
        //    (and zombies) can walk up the middle.
        int budget = Mathf.Min(ctx.PropBudget(), 16);
        const float deskW = 1.0f, deskD = 0.6f, runGap = 0.7f, depthGap = 1.15f, aisleHalf = 0.7f;

        // Rows march from near the back wall toward the front, stopping short of the
        // teacher desk. "d" is the world coord on the depth axis for the row.
        // (Guard against a degenerate room so the depth loop always terminates.)
        if (Mathf.Abs(depthSign) < 0.5f) return;
        float firstRow = backCoord + depthSign * 1.2f;
        float lastRow = teacherDepth - depthSign * 1.7f; // gap in front of the teacher
        int row = 0;
        for (float d = firstRow;
             depthSign > 0 ? d <= lastRow : d >= lastRow;
             d += depthSign * depthGap, row++)
        {
            if (ctx.PropCount >= budget) break;
            int col = 0;
            for (float r = runMin + deskW * 0.5f; r + deskW * 0.5f <= runMax && ctx.PropCount < budget; r += deskW + runGap, col++)
            {
                // Keep a clear central aisle (skip desks straddling the run centre).
                if (Mathf.Abs(r - runCenter) < aisleHalf) continue;

                float dx = depthIsZ ? r : d;
                float dz = depthIsZ ? d : r;
                // Footprint half-extents follow the desk's facing: width spans the run
                // axis, depth spans the depth axis.
                float hX = depthIsZ ? deskW * 0.5f + 0.05f : deskD * 0.5f + 0.05f;
                float hZ = depthIsZ ? deskD * 0.5f + 0.05f : deskW * 0.5f + 0.05f;
                int rr = row, cc = col;
                if (PlaceAt(ctx, dx, dz, hX, hZ, p => MakeDesk(ctx, p, studentYaw, $"Desk_{rr}_{cc}")))
                {
                    // Chair tucked behind the desk (away from the board) facing it.
                    Vector3 cp = new Vector3(dx, ctx.FloorY, dz) + (-boardDir) * 0.55f;
                    if (ctx.Fits(cp.x, cp.z, 0.28f, 0.28f)) MakeChair(ctx, cp, studentYaw, $"Chair_{rr}_{cc}");
                }
            }
        }
    }

    private static void FurnishLab(RoomContext ctx)
    {
        // Whiteboard + a sink counter run along the front wall.
        MakeWhiteboard(ctx, Wall.North, "Whiteboard");
        MakeCounterRun(ctx, Wall.North, "SinkCounter", withSink: true);

        // Wall cabinets along a side wall.
        MakeCounterRun(ctx, Wall.West, "WallCabinets", withSink: false);

        // Equipment shelves in a corner.
        PlaceInCorner(ctx, 1, 1.2f, 0.4f, (pos, yaw) => MakeShelf(ctx, pos, yaw, "EquipShelf"));

        // Lab benches with stools down the middle (two rows, wide aisle).
        int budget = Mathf.Min(ctx.PropBudget(), 8);
        const float benchW = 2.2f, benchD = 0.8f, gapZ = 2.0f;
        float[] lanes = { ctx.Center.x - ctx.SizeX * 0.22f, ctx.Center.x + ctx.SizeX * 0.22f };
        int idx = 0;
        for (float z = ctx.MinZ + 1.4f; z <= ctx.MaxZ - 2.0f && ctx.PropCount < budget; z += gapZ)
        {
            foreach (float laneX in lanes)
            {
                if (ctx.PropCount >= budget) break;
                if (PlaceAt(ctx, laneX, z, benchW * 0.5f + 0.05f, benchD * 0.5f + 0.05f,
                        p => MakeTable(ctx, p, 0f, benchW, benchD, 0.9f, _matMetalGrey, $"LabBench_{idx}")))
                {
                    // A stool on each long side.
                    Vector3 s1 = new Vector3(laneX, ctx.FloorY, z + benchD * 0.5f + 0.35f);
                    Vector3 s2 = new Vector3(laneX, ctx.FloorY, z - benchD * 0.5f - 0.35f);
                    if (ctx.Fits(s1.x, s1.z, 0.25f, 0.25f)) MakeStool(ctx, s1, $"Stool_{idx}a");
                    if (ctx.Fits(s2.x, s2.z, 0.25f, 0.25f)) MakeStool(ctx, s2, $"Stool_{idx}b");
                    idx++;
                }
            }
        }
    }

    private static void FurnishConference(RoomContext ctx)
    {
        // One long central table with chairs around it; a cabinet against a wall.
        float tableLen = Mathf.Clamp(ctx.SizeZ * 0.6f, 2.5f, 6f);
        float tableW = Mathf.Clamp(ctx.SizeX * 0.35f, 1.0f, 1.8f);
        Vector3 c = new Vector3(ctx.Center.x, ctx.FloorY, ctx.Center.z);

        if (PlaceAt(ctx, c.x, c.z, tableW * 0.5f + 0.1f, tableLen * 0.5f + 0.1f,
                p => MakeTable(ctx, p, 0f, tableW, tableLen, 0.75f, _matWoodMid, "ConferenceTable")))
        {
            // Chairs down both long sides.
            int perSide = Mathf.Max(2, Mathf.FloorToInt(tableLen / 1.0f));
            for (int i = 0; i < perSide; i++)
            {
                float z = Mathf.Lerp(c.z - tableLen * 0.5f + 0.5f, c.z + tableLen * 0.5f - 0.5f, perSide == 1 ? 0.5f : i / (float)(perSide - 1));
                Vector3 left = new Vector3(c.x - tableW * 0.5f - 0.4f, ctx.FloorY, z);
                Vector3 right = new Vector3(c.x + tableW * 0.5f + 0.4f, ctx.FloorY, z);
                if (ctx.Fits(left.x, left.z, 0.28f, 0.28f)) MakeChair(ctx, left, 90f, $"Chair_L{i}");
                if (ctx.Fits(right.x, right.z, 0.28f, 0.28f)) MakeChair(ctx, right, 270f, $"Chair_R{i}");
            }
        }

        PlaceInCorner(ctx, 0, 1.2f, 0.45f, (pos, yaw) => MakeCabinet(ctx, pos, yaw, "Cabinet"));
    }

    private static void FurnishCafeteria(RoomContext ctx)
    {
        // Food-service line set ~1.2m OFF the north wall so the player can walk
        // behind it (server side). Stop the dining rows short of it.
        const float counterOffset = 1.2f, counterDepth = 0.6f;
        MakeCounterRun(ctx, Wall.North, "FoodCounter", withSink: false, wallOffset: counterOffset);
        float counterFrontZ = ctx.MaxZ - (counterOffset + counterDepth); // inner face of the line

        // Several long tables with bench seats, in neat parallel rows with walking
        // gaps; kept clear of the service line and doorways (Fits handles doors).
        int budget = Mathf.Min(ctx.PropBudget(), 12);
        float tableLen = Mathf.Clamp(ctx.SizeX * 0.5f, 2.5f, 5f);
        const float tableW = 0.9f, rowGap = 2.2f;
        int idx = 0;
        float diningMaxZ = Mathf.Min(ctx.MaxZ - 2.4f, counterFrontZ - 1.0f);
        for (float z = ctx.MinZ + 1.4f; z <= diningMaxZ && ctx.PropCount < budget; z += rowGap)
        {
            float x = ctx.Center.x;
            if (PlaceAt(ctx, x, z, tableLen * 0.5f + 0.1f, tableW * 0.5f + 0.45f,
                    p => MakeTable(ctx, p, 90f, tableW, tableLen, 0.75f, _matWoodMid, $"CafeTable_{idx}")))
            {
                // A bench on each long side. The table runs along world X (it was
                // yawed 90), so benches run along world X too -> bench yaw 0.
                Vector3 b1 = new Vector3(x, ctx.FloorY, z + tableW * 0.5f + 0.32f);
                Vector3 b2 = new Vector3(x, ctx.FloorY, z - tableW * 0.5f - 0.32f);
                if (ctx.Fits(b1.x, b1.z, tableLen * 0.45f, 0.18f)) MakeBench(ctx, b1, 0f, tableLen * 0.9f, $"Bench_{idx}a");
                if (ctx.Fits(b2.x, b2.z, tableLen * 0.45f, 0.18f)) MakeBench(ctx, b2, 0f, tableLen * 0.9f, $"Bench_{idx}b");
                idx++;
            }
        }

        // A trash can + a spilled trays crate near a corner.
        PlaceInCorner(ctx, 2, 0.3f, 0.3f, (pos, yaw) => MakeTrashCan(ctx, pos, "TrashCan"));
        PlaceInCorner(ctx, 3, 0.5f, 0.5f, (pos, yaw) => MakeCrate(ctx, pos, 0.6f, "TrayCrate"));
    }

    private static void FurnishKitchen(RoomContext ctx)
    {
        // Prep/sink line set ~1.2m off the north wall so the player can walk behind
        // it. The south wall keeps a flush back-counter, preserving a clear central
        // working lane (and never blocking the kitchen entrance - Fits clears doors).
        const float counterOffset = 1.2f;
        MakeCounterRun(ctx, Wall.North, "PrepCounterN", withSink: true, wallOffset: counterOffset);
        MakeCounterRun(ctx, Wall.South, "PrepCounterS", withSink: false, wallOffset: 0f);

        // Storage shelves on a side wall.
        MakeWallShelfRun(ctx, Wall.West, "StorageShelves");

        // A prep-table island only when the room is deep enough that the offset
        // north line + island + south counter still leave walking lanes.
        if (ctx.SizeX > 3f && ctx.SizeZ > 5.5f)
        {
            Vector3 c = ctx.Center;
            PlaceAt(ctx, c.x, c.z, 0.9f, 0.6f,
                p => MakeTable(ctx, p, 0f, 1.6f, 1.0f, 0.9f, _matMetalGrey, "PrepIsland"));
        }

        // Stacked crates in a corner.
        PlaceInCorner(ctx, 1, 0.5f, 0.5f, (pos, yaw) => MakeCrateStack(ctx, pos, "CrateStack"));
    }

    private static void FurnishLibrary(RoomContext ctx)
    {
        // Rows of tall bookshelves with wide aisles, running along Z.
        int budget = Mathf.Min(ctx.PropBudget(), 14);
        const float shelfLen = 2.4f, shelfDepth = 0.4f, aisle = 1.8f, colGap = aisle + shelfDepth;
        int col = 0;
        for (float x = ctx.MinX + 1.0f; x + shelfDepth * 0.5f <= ctx.MaxX - 0.5f && ctx.PropCount < budget; x += colGap, col++)
        {
            int row = 0;
            for (float z = ctx.MinZ + shelfLen * 0.5f + 0.3f; z + shelfLen * 0.5f <= ctx.MaxZ - 0.3f && ctx.PropCount < budget; z += shelfLen + 0.5f, row++)
            {
                // Shelves run long along Z (thin along X); MakeBookshelf builds its
                // length along local X, so yaw 90 maps that length onto world Z to
                // match the footprint validated above.
                PlaceAt(ctx, x, z, shelfDepth * 0.5f + 0.05f, shelfLen * 0.5f + 0.05f,
                    p => MakeBookshelf(ctx, p, 90f, shelfLen, $"Bookshelf_{col}_{row}"));
            }
        }

        // A couple of study tables with chairs near a wall, if there's room left.
        if (ctx.SizeX > 4f && ctx.SizeZ > 3f && ctx.PropCount < budget)
        {
            float x = ctx.MaxX - 1.2f;
            float z = ctx.Center.z;
            if (PlaceAt(ctx, x, z, 0.7f, 0.5f, p => MakeTable(ctx, p, 0f, 1.4f, 0.9f, 0.75f, _matWoodMid, "StudyTable")))
            {
                // Chair south of the table, facing the table (north, +Z).
